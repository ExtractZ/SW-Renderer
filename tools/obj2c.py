#!/usr/bin/env python3
"""Generates a C mesh file (Core/Src/mesh_<name>.c) for the renderer.

Two sources:
  torus  generated from a formula, no download needed
           python3 tools/obj2c.py torus --name torus --rings 24 --sides 12
  obj    converted from a Wavefront .obj file (the most common 3D model format)
           python3 tools/obj2c.py obj models/teapot.obj --name teapot

Output: vertices and per-vertex normals in Q16.16, triangles as index triples,
wound counter-clockwise seen from outside (what render.c's culling expects).
Then declare it in mesh.h:  extern const mesh mesh_<name>;
"""
import argparse
import math
import os

ONE = 1 << 16  # 1.0 in Q16.16
MAX_VERTS = 1024  # RENDER_MAX_VERTS in render.h


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def normalize(v):
    length = math.sqrt(dot(v, v))
    return (v[0] / length, v[1] / length, v[2] / length) if length > 0 else (0.0, 0.0, 0.0)


def torus(major, minor, rings, sides):
    """Ring around the y axis. u goes around the ring, v around the tube."""
    verts, normals, tris = [], [], []
    for i in range(rings):
        u = 2 * math.pi * i / rings
        for j in range(sides):
            v = 2 * math.pi * j / sides
            n = (math.cos(v) * math.cos(u), math.sin(v), math.cos(v) * math.sin(u))
            verts.append(((major + minor * math.cos(v)) * math.cos(u),
                          minor * math.sin(v),
                          (major + minor * math.cos(v)) * math.sin(u)))
            normals.append(n)

    def idx(i, j):
        return (i % rings) * sides + (j % sides)

    for i in range(rings):
        for j in range(sides):
            a, b, c, d = idx(i, j), idx(i + 1, j), idx(i + 1, j + 1), idx(i, j + 1)
            tris += [(a, b, c), (a, c, d)]

    # make every triangle counter-clockwise from outside: its face normal
    # must point the same way as the surface normal at its corners
    fixed = []
    for t in tris:
        face = cross(sub(verts[t[1]], verts[t[0]]), sub(verts[t[2]], verts[t[0]]))
        avg = tuple(sum(normals[k][axis] for k in t) for axis in range(3))
        fixed.append(t if dot(face, avg) > 0 else (t[0], t[2], t[1]))
    return verts, normals, fixed


def load_obj(path, flip):
    """Reads v and f lines (polygons are split into triangles). Normals are
    recomputed by averaging the faces around each vertex."""
    verts, tris = [], []
    with open(path) as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "v":
                verts.append(tuple(float(x) for x in parts[1:4]))
            elif parts[0] == "f":
                # "f 1/2/3 4/5/6 ..." -> vertex index is before the first slash, 1-based,
                # negative = counted from the end
                ids = []
                for p in parts[1:]:
                    k = int(p.split("/")[0])
                    ids.append(k - 1 if k > 0 else len(verts) + k)
                for k in range(1, len(ids) - 1):  # fan: (0,1,2), (0,2,3), ...
                    t = (ids[0], ids[k], ids[k + 1])
                    tris.append((t[0], t[2], t[1]) if flip else t)

    # center the model and scale it to fit in a radius of 1.4 (like the torus)
    center = tuple((min(v[a] for v in verts) + max(v[a] for v in verts)) / 2 for a in range(3))
    verts = [sub(v, center) for v in verts]
    radius = max(math.sqrt(dot(v, v)) for v in verts)
    verts = [tuple(c * 1.4 / radius for c in v) for v in verts]

    # vertex normal = sum of the (area-weighted) normals of the faces touching it
    acc = [[0.0, 0.0, 0.0] for _ in verts]
    for t in tris:
        face = cross(sub(verts[t[1]], verts[t[0]]), sub(verts[t[2]], verts[t[0]]))
        for k in t:
            for a in range(3):
                acc[k][a] += face[a]
    normals = [normalize(n) for n in acc]
    return verts, normals, tris


def fx(x):
    return int(round(x * ONE))


def write_c(name, verts, normals, tris, source):
    if len(verts) > MAX_VERTS:
        print(f"warning: {len(verts)} vertices > RENDER_MAX_VERTS ({MAX_VERTS}); render.c will skip it")

    def vec_rows(vs):
        return "\n".join(f"\t{{ {fx(v[0])}, {fx(v[1])}, {fx(v[2])} }}," for v in vs)

    tri_rows = "\n".join(f"\t{{ {t[0]}, {t[1]}, {t[2]} }}," for t in tris)
    text = f"""// Generated by tools/obj2c.py -- do not edit by hand
// {source}: {len(verts)} vertices, {len(tris)} triangles
#include "mesh.h"

static const vec3 {name}_verts[{len(verts)}] = {{
{vec_rows(verts)}
}};

static const vec3 {name}_normals[{len(verts)}] = {{
{vec_rows(normals)}
}};

static const uint16_t {name}_tris[{len(tris)}][3] = {{
{tri_rows}
}};

const mesh mesh_{name} = {{
	.verts = {name}_verts,
	.normals = {name}_normals,
	.tris = {name}_tris,
	.tri_colors = 0,
	.num_verts = {len(verts)},
	.num_tris = {len(tris)},
}};
"""
    out = os.path.join(os.path.dirname(__file__), "..", "Core", "Src", f"mesh_{name}.c")
    with open(out, "w") as f:
        f.write(text)
    print(f"wrote {len(verts)} vertices, {len(tris)} triangles to {os.path.normpath(out)}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = p.add_subparsers(dest="source", required=True)

    t = sp.add_parser("torus")
    t.add_argument("--name", default="torus")
    t.add_argument("--major", type=float, default=1.0, help="ring radius")
    t.add_argument("--minor", type=float, default=0.4, help="tube radius")
    t.add_argument("--rings", type=int, default=24, help="segments around the ring")
    t.add_argument("--sides", type=int, default=12, help="segments around the tube")

    o = sp.add_parser("obj")
    o.add_argument("path")
    o.add_argument("--name", required=True)
    o.add_argument("--flip", action="store_true", help="reverse winding (if the model renders inside-out)")

    args = p.parse_args()
    if args.source == "torus":
        verts, normals, tris = torus(args.major, args.minor, args.rings, args.sides)
        source = f"torus R={args.major} r={args.minor} {args.rings}x{args.sides}"
    else:
        verts, normals, tris = load_obj(args.path, args.flip)
        source = os.path.basename(args.path)
    write_c(args.name, verts, normals, tris, source)


if __name__ == "__main__":
    main()
